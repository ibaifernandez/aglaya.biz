#!/usr/bin/env node
/**
 * Bridges the canonical AGLAYA tokens into Tailwind v4's `@theme` namespace.
 *
 * Why this file exists at all: Tailwind v4 only generates utilities (`bg-brand`,
 * `text-corporate-green`, …) for custom properties declared inside `@theme`. The
 * canon ships its tokens in `:root`, which Tailwind does not read. This script
 * is the only bridge — it copies NAMES, and reads VALUES from the installed
 * package at build time.
 *
 * The output is never committed (see .gitignore). A committed copy would pass
 * every check except the one that decides — moving a value in the design system
 * and rebuilding here would keep painting the old colour.
 *
 * Source of truth: @aglaya/design-tokens (git tag). Nothing here hardcodes a
 * brand value, and a `guard` below fails the build if one ever sneaks in.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { tokens, version } from '@aglaya/design-tokens';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO_ROOT, 'src/styles/tokens.theme.generated.css');

/**
 * Tailwind namespaces this site actually consumes. Deliberately narrow:
 *
 * - `--color-*`  → bg-/text-/border-/stroke- utilities (the 376 existing uses).
 * - `--font-*`   → font-display / font-body / font-mono.
 * - `--radius-*` → rounded-* (all zero by brand rule, plus radius-full).
 *
 * Everything else the canon publishes (--text-*, --tracking-*, --space-*,
 * --ease-*, --glow-*, --layout-*) stays reachable as plain `var()` through the
 * canon's own `:root`. It is NOT bridged, for two reasons: `--text-*` is
 * Tailwind's font-size namespace and the canon's values are `font:` shorthands
 * (they would compile to broken utilities), and bridging the rest would hand
 * this site new capability it never asked for. Cabling the brand, nothing else.
 */
const BRIDGED = [/^--color-/, /^--font-/, /^--radius-/];

/**
 * Product accents are published by the canon but MUST NOT reach this surface.
 * aglaya.biz is the marca-madre: three colours, per the master non-negotiables
 * (`get_nonnegotiables("master")`). The accents are first-class only on their
 * own product's surface. This is an explicit refusal, not an oversight.
 */
const REFUSED = [/^--product-/];

const selected = Object.entries(tokens)
  .filter(([name]) => !REFUSED.some((re) => re.test(name)))
  .filter(([name]) => BRIDGED.some((re) => re.test(name)));

if (selected.length === 0) {
  throw new Error(
    'No tokens matched the Tailwind bridge. The package shape changed — ' +
      'read node_modules/@aglaya/design-tokens/docs/PACKAGE.md before "fixing" this.',
  );
}

// A leaked product accent would be a silent brand violation, so it fails loud.
const leaked = Object.keys(tokens).filter(
  (name) => REFUSED.some((re) => re.test(name)) && selected.some(([n]) => n === name),
);
if (leaked.length > 0) {
  throw new Error(`Product accents must not reach the master surface: ${leaked.join(', ')}`);
}

const body = selected.map(([name, value]) => `  ${name}: ${value};`).join('\n');

const css = `/* GENERATED by scripts/generate-tailwind-theme.mjs — do not edit, do not commit.
   Source: @aglaya/design-tokens@${version} (${selected.length} of ${Object.keys(tokens).length} tokens bridged).
   Names live here; values come from the package on every build. */
@theme {
${body}
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css, 'utf8');

console.log(
  `[tokens] bridged ${selected.length} tokens from @aglaya/design-tokens@${version} → src/styles/tokens.theme.generated.css`,
);
